import { SwatchColor, ColorPaletteOptions } from './types';

export function rgbToHex(r: number, g: number, b: number): string {
  const toHex = (n: number) => n.toString(16).padStart(2, '0');
  return `#${toHex(r)}${toHex(g)}${toHex(b)}`.toUpperCase();
}

export function rgbToHsl(r: number, g: number, b: number): [number, number, number] {
  r /= 255;
  g /= 255;
  b /= 255;
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  let h = 0;
  let s = 0;
  const l = (max + min) / 2;

  if (max !== min) {
    const d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    switch (max) {
      case r:
        h = (g - b) / d + (g < b ? 6 : 0);
        break;
      case g:
        h = (b - r) / d + 2;
        break;
      case b:
        h = (r - g) / d + 4;
        break;
    }
    h /= 6;
  }

  return [Math.round(h * 360), Math.round(s * 100), Math.round(l * 100)];
}

function colorDistance(c1: [number, number, number], c2: [number, number, number]): number {
  const dr = c1[0] - c2[0];
  const dg = c1[1] - c2[1];
  const db = c1[2] - c2[2];
  return Math.sqrt(dr * dr + dg * dg + db * db);
}

/**
 * Extracts dominant color palette from an HTMLImageElement
 */
export function extractColorPalette(
  img: HTMLImageElement,
  options: ColorPaletteOptions
): SwatchColor[] {
  const canvas = document.createElement('canvas');
  // Sample at 120x120 for instant responsiveness
  const sampleSize = 120;
  canvas.width = sampleSize;
  canvas.height = sampleSize;
  const ctx = canvas.getContext('2d', { willReadFrequently: true });
  if (!ctx) return [];

  ctx.drawImage(img, 0, 0, sampleSize, sampleSize);
  const imgData = ctx.getImageData(0, 0, sampleSize, sampleSize);
  const data = imgData.data;

  // Bucket colors by quantizing RGB channels into 16-level buckets
  const bucketMap = new Map<string, { r: number; g: number; b: number; count: number }>();
  let totalValidPixels = 0;

  for (let i = 0; i < data.length; i += 4) {
    const a = data[i + 3];
    if (a < 128) continue; // Ignore transparent pixels

    const r = data[i];
    const g = data[i + 1];
    const b = data[i + 2];

    // Quantize to steps of 16
    const qr = Math.round(r / 16) * 16;
    const qg = Math.round(g / 16) * 16;
    const qb = Math.round(b / 16) * 16;
    const key = `${qr}-${qg}-${qb}`;

    const existing = bucketMap.get(key);
    if (existing) {
      existing.r += r;
      existing.g += g;
      existing.b += b;
      existing.count++;
    } else {
      bucketMap.set(key, { r, g, b, count: 1 });
    }
    totalValidPixels++;
  }

  // Convert buckets to average colors
  const candidates: { rgb: [number, number, number]; count: number }[] = [];
  bucketMap.forEach((val) => {
    candidates.push({
      rgb: [
        Math.round(val.r / val.count),
        Math.round(val.g / val.count),
        Math.round(val.b / val.count),
      ],
      count: val.count,
    });
  });

  // Sort by raw frequency
  candidates.sort((a, b) => b.count - a.count);

  // Filter out visually identical colors (minimum Euclidean distance of 36)
  const distinctColors: { rgb: [number, number, number]; count: number }[] = [];
  for (const cand of candidates) {
    if (distinctColors.length >= options.colorCount) break;

    const isTooClose = distinctColors.some(
      (existing) => colorDistance(existing.rgb, cand.rgb) < 38
    );

    if (!isTooClose) {
      distinctColors.push(cand);
    }
  }

  // Format into final swatches
  let swatches: SwatchColor[] = distinctColors.map((item) => {
    const [r, g, b] = item.rgb;
    return {
      hex: rgbToHex(r, g, b),
      rgb: [r, g, b],
      hsl: rgbToHsl(r, g, b),
      percentage: Math.round((item.count / totalValidPixels) * 100),
    };
  });

  // Sort according to user preference
  if (options.sortOrder === 'hue') {
    swatches.sort((a, b) => a.hsl[0] - b.hsl[0]);
  } else if (options.sortOrder === 'luminance') {
    swatches.sort((a, b) => a.hsl[2] - b.hsl[2]);
  }

  return swatches;
}

/**
 * Generates an exportable PNG image swatch card
 */
export function generateSwatchCardImage(swatches: SwatchColor[], title: string): string {
  const cardWidth = 800;
  const swatchHeight = 160;
  const padding = 32;
  const cardHeight = padding * 2 + 50 + swatchHeight + 60;

  const canvas = document.createElement('canvas');
  canvas.width = cardWidth;
  canvas.height = cardHeight;
  const ctx = canvas.getContext('2d');
  if (!ctx) return '';

  // Background
  ctx.fillStyle = '#0f172a';
  ctx.fillRect(0, 0, cardWidth, cardHeight);

  // Title
  ctx.fillStyle = '#ffffff';
  ctx.font = 'bold 20px sans-serif';
  ctx.fillText(title || 'Color Palette Swatches', padding, padding + 22);

  ctx.fillStyle = '#94a3b8';
  ctx.font = '13px sans-serif';
  ctx.fillText('Generated by Tools Arena Color Studio', padding, padding + 44);

  // Swatch row
  const swatchAreaWidth = cardWidth - padding * 2;
  const colWidth = swatchAreaWidth / swatches.length;
  const topY = padding + 60;

  swatches.forEach((swatch, idx) => {
    const x = padding + idx * colWidth;

    // Color block
    ctx.fillStyle = swatch.hex;
    ctx.fillRect(x, topY, colWidth, swatchHeight);

    // Label below
    ctx.fillStyle = '#ffffff';
    ctx.font = 'bold 13px monospace';
    ctx.fillText(swatch.hex, x + 8, topY + swatchHeight + 24);

    ctx.fillStyle = '#94a3b8';
    ctx.font = '11px sans-serif';
    ctx.fillText(`${swatch.rgb.join(', ')}`, x + 8, topY + swatchHeight + 42);
  });

  return canvas.toDataURL('image/png');
}
